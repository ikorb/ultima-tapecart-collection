;;; efpage.s -- the EasyFlash cart's launcher: one page for Ultima VI.
;;;
;;; efstart.s copies it from bank 0 to PAGE_ORG and jumps here, with the
;;; KERNAL initialised (efstub.s), the cart off.  It offers:
;;;
;;;   L  launch: the game's own title, its menu, character creation
;;;   J  Journey onward: straight into the saved game (only with one)
;;;   E  export the saved game: to the game's own disks, to a file, or to
;;;      the tapecart's Ultima collection, both carts plugged in
;;;   I  import one, from any of them
;;;   R  reset the world: a new, empty log
;;;   5  Ultima V from the tapecart, both carts plugged in, with its music
;;;      and 2-bit reads from this cart (efu5.s; only in a build that had
;;;      Ultima V's disks)
;;;
;;; E and I are the tapecart launcher's own (asm/page_xfer.s, page_u6x.s,
;;; page_file.s, included unchanged): the same prompts, the same disks and
;;; file format, the same rules (an import goes into the log's other half
;;; and makes it the active one last).  What they ask of page.s is here,
;;; what they ask of tclib is eflib.s -- DIR_LOOKUP answered from the flash,
;;; writes and erases through EAPI.  The other games' parts of page_xfer.s
;;; are assembled and never reached; their symbols are stubs (efpage_data.s
;;; and below).
;;;
;;; The tapecart's log has the same entries as this one, so to and from it
;;; is the disk import's loop with the other cart's log in the drive's
;;; place (tx_copy); eftc.s is its tclib, which eflib switches to.
;;;
;;; L and J put efinit.s at $1000 (with Journey onward's pokes in its
;;; table), the machine as the stub left it, and jump there.
;;;
;;; Memory: $0400-$07FF the transfer code's buffers (U6's BAM $0500, a
;;; sector $0600, the settings $0700), $0800-$2FFF BUF and ORIG
;;; (page_u6x.s), the screen at $4400 in VIC bank 1 with Ultima VI's
;;; text-box font at $4800, this from $5000 (eflib below $8000), the
;;; tapecart's tclib at TCX_ORG while it is used (eftc.s), EAPI at $C000,
;;; efu5.s at U5L_ORG once 5 is picked.

!source "efvars.inc"

PAGE_ORG = $5000
BUF      = $0800
SCREEN   = $4400
CHARS    = $4800
EL_SLOT  = $c000                ; EAPI's home while the launcher runs

CHROUT = $ffd2
SCNKEY = $ff9f
GETIN  = $ffe4
PLOT   = $fff0
IOINIT = $ff84
RESTOR = $ff8a
CINT   = $ff81

ptr  = $fb
ptr2 = $fd

G_U1 = 0                        ; descriptor indices, as page.s
G_U3 = 1
G_U2 = 2
G_U4 = 3
G_U5 = 4
G_U6 = 5
ENTRY = KEYLEN + DATALEN

EFLIB_WRITE = 1
EFLIB_TC    = 1                 ; and the tapecart (TCX_ORG: ultima/ef/build.py)

        * = PAGE_ORG
        jmp main

!source "eflib.s"               ; first: it maps the cart, so below $8000
eflib_end:
!if eflib_end > $8000 {
        !error "eflib runs into the cart's window at $8000 by ", eflib_end - $8000
}
!source "efpage_data.s"         ; generated by ultima/ef/build.py
!source "page_xfer.s"
!source "page_u6x.s"
!source "page_file.s"

main:   sei
        lda #$37
        sta $01
        lda #EF_OFF
        sta el_idle
        sta EF_CTRL_REG
        ldx #$fb
        txs
        jsr screen
        jsr ef_init
        lda #$00
        rol
        sta noeapi
        ldx #$00                ; the settings: drive 8, nothing else kept
        txa
-       sta setbuf,x
        inx
        bne -
        lda #G_U6
        sta gid

redraw: jsr draw
keys:   jsr getkey
        cmp #"L"
        bne +
        lda #$00
        jmp launch
+       cmp #"J"                ; (J and E: only with a saved game, as on
        bne +                   ; the tapecart's page)
        lda has_save
        beq keys
        lda #$01
        jmp launch
+       cmp #"E"
        bne +
        lda has_save
        beq keys
        jmp ex_ask
+       cmp #"I"
        bne +
        jsr can_write
        bcs keys
        jmp im_ask
!ifdef U5L_SRC {
+       cmp #"5"
        bne +
        jmp u5_go
}
+       cmp #"R"
        bne keys
        jsr can_write
        bcs keys
        jmp ask_reset

;;; C clear if the cart can be written; if not, said so
can_write:
        lda noeapi
        bne +
        clc
        rts
+       jsr p_area
        jsr pr
        !pet 13," This cartridge's flash is not one its",13
        !pet " EAPI knows: nothing can be saved.",0
        sec
        rts

;;; ---- the page ---------------------------------------------------------
;;; As the tapecart's (page.s): the keys white, the rest light grey; the
;;; party, then the commands -- J and E only with a saved game
WHITE = 5
GREY  = 155

draw:   jsr dev_ef              ; (every way back from a transfer)
        lda #$93
        jsr CHROUT
        jsr pr
        !pet WHITE,13,"   Ultima VI",13
        !pet GREY,"   on EasyFlash",13,13,0
        jsr i_u6
        lda has_save
        bne +
        jsr pr
        !pet "   No saved game",13,0
+       jsr pr
        !pet 13,"   ",WHITE,"L",GREY,"  Launch the game",13,0
        lda has_save
        beq +
        jsr pr
        !pet "   ",WHITE,"J",GREY,"  Journey onward",13,0
+       lda #13
        jsr CHROUT
        lda has_save
        beq +
        jsr pr
        !pet "   ",WHITE,"E",GREY,"  Export the saved game",13,0
+       jsr pr
        !pet "   ",WHITE,"I",GREY,"  Import a saved game",13
        !pet "   ",WHITE,"R",GREY,"  Reset the world",13,13,0
!ifdef U5L_SRC {
        jsr pr
        !pet "   ",WHITE,"5",GREY,"  Ultima V (tapecart) with music",13,13,0
}
        jsr pr                  ; which EAPI EasyProg put in: its version
        !pet "   EAPI: ",0           ; string (ProgRef: offset 4, 16 bytes, 0
        ldx #$00                ; terminated)
-       lda EL_SLOT+4,x
        beq +
        jsr CHROUT
        inx
        cpx #16
        bne -
+       lda noeapi
        beq +
        jsr pr
        !pet " (not this flash)",0
+       lda #13
        jsr CHROUT
        lda el_werr
        beq +
        lda #$00
        sta el_werr
        jsr pr
        !pet 13,"   A write to the cartridge failed:",13
        !pet "   the saved game may be the old one.",13,0
+       lda $d6                 ; questions go below
        sta brow
        rts

;;; A question goes in the rows from brow on, which are cleared (page.s)
p_area: lda brow
        sta crow
-       ldx crow
        ldy #$00
        clc
        jsr PLOT
        ldy #39
--      lda #" "
        jsr CHROUT
        dey
        bne --
        inc crow
        lda crow
        cmp #24
        bcc -
        ldx brow
        ldy #$00
        clc
        jmp PLOT

;;; VIC bank 1: the screen at $4400 and the font at $4800 -- Ultima VI's
;;; text-box font from its intro and ending (ICHARS, ultima/ef/build.py) -- white on
;;; black
screen: ldx #rd_font + 6 - rd_rows
        jsr rd7
        lda $dd00
        and #%11111100
        ora #%00000010          ; bank 1: $4000-$7FFF
        sta $dd00
        lda #$12                ; screen +$0400, characters +$0800
        sta $d018
        lda #>SCREEN
        sta $0288
        lda #$00
        sta $d020
        sta $d021
        lda #$0e                ; (the cursor colour)
        sta $0286
        lda #$08                ; no case switch with C= and SHIFT
        jsr CHROUT
        lda #$0e                ; (lower case: already the characters)
        jmp CHROUT

;;; ---- L and J -------------------------------------------------------------
launch: sta jo
        ldx #rd_efi + 6 - rd_rows
        jsr rd7
        lda jo
        beq +
        ldx #6                  ; Journey onward: two pokes into its table
-       lda jo_pokes,x
        sta EFI_POKES,x
        dex
        bpl -
+       sei                     ; the machine as the stub left it
        jsr IOINIT
        jsr RESTOR
        jsr CINT
        sei
        lda #$37
        sta $01
        lda #EF_16K
        sta EF_CTRL_REG
        jmp $1000

;;; the cold start's LDA #$00 / BNE $C036 at $C023 made BEQ $C054: the
;;; game and its saved world, past the opening (ultima/games/u6/build.py)
jo_pokes:
        !byte 3 * 2
        !byte <$c025, >$c025, $f0
        !byte <$c026, >$c026, $c054 - $c027

;;; ---- R --------------------------------------------------------------------
ask_reset:
        jsr p_area
        jsr pr
        !pet 13," Reset: the saved game is erased, and",13
        !pet " the world is the game's own again.",13
        !pet " (Y/N) ",0
        jsr yn_key
        cmp #"Y"
        beq +
        jmp redraw
+       jsr x6_begin            ; the other half, erased (" Clearing")
        jsr x6_commit           ; its header: an empty log; the old erased
        jmp x_done2

;;; The export tables come in with the launcher (efpage_data.s) and end in
;;; x_magic: refuse, rather than export or import by whatever RAM holds
;;; there, if they are not.
x_tables:
        ldx #3
-       lda x_magic,x
        cmp f_magic,x
        bne +
        dex
        bpl -
        rts
+       pla                     ; not back to the caller
        pla
        jsr pr
        !pet 13," The export tables are missing: this",13
        !pet " cartridge needs the full .tcrt image.",0
        jmp x_key

;;; ---- E and I: the disks, a file, or the tapecart ------------------------
;;; D and F go on as page_file.s's f_export_ask and f_import_ask do
ex_ask: jsr p_area
        jsr x_tables
        jsr pr
        !pet 13," Export to the game's own (D)isks, to a",13
        !pet " (F)ile on any disk, or to the",13
        !pet " (T)apecart? RUN/STOP cancels. ",0
        jsr dft_key
        bcc +
        jmp redraw
+       cmp #"D"
        bne +
        jmp x6_export
+       cmp #"F"
        bne +
        jmp f_export
+       jmp tx_export

im_ask: jsr p_area
        jsr x_tables
        jsr pr
        !pet 13," Import from the game's own (D)isks,",13
        !pet " from a (F)ile on any disk, or from the",13
        !pet " (T)apecart? RUN/STOP cancels. ",0
        jsr dft_key
        bcc +
        jmp redraw
+       cmp #"D"
        bne +
        jmp x6_import
+       cmp #"F"
        bne +
        jmp f_import
+       jmp tx_import

;;; D, F or T in A, C clear; C set for RUN/STOP and <-; other keys are not
;;; taken (page_file.s df_key)
dft_key:
        jsr getkey
        cmp #"D"
        beq ++
        cmp #"F"
        beq ++
        cmp #"T"
        beq ++
        cmp #$03                ; RUN/STOP
        beq +
        cmp #$5f                ; <-
        bne dft_key
+       sec
        rts
++      clc
        rts

;;; ---- to and from the tapecart -------------------------------------------
;;; The tapecart's Ultima collection keeps Ultima VI's world in a write log
;;; with this one's entries (page_u6x.s), at its own place (regions.py).  A
;;; key neither log has is the original on both carts, so a copy is the
;;; disk import's loop with the source cart's log in the drive's place: each
;;; chunk file and save-area sector the source has logged, if it differs
;;; from the original, into the destination's other half, which its header
;;; makes the one in use last -- a copy that stops half way leaves the
;;; destination's world as it was.  Only a saved game is taken (the save
;;; area's S12 and S13 logged): an empty source would reset the world.
tx_export:
        jsr tx_open
        bcc +
        jmp x_key
+       lda #$00                ; from here
        sta tx_src
        lda #$80                ; to the tapecart
        sta tx_dst
        jsr tx_find
        jsr pr
        !pet 13," Export: this replaces the world on",13
        !pet " the tapecart. (Y/N) ",0
        jmp tx_go

tx_import:
        jsr tx_open
        bcc +
        jmp x_key
+       lda #$80                ; from the tapecart
        sta tx_src
        lda #$00                ; to here
        sta tx_dst
        jsr tx_find
        bcc +
        jsr pr
        !pet 13," The tapecart has no saved game of",13
        !pet " Ultima VI.",0
        jmp x_key
+       jsr pr
        !pet 13," Import: this replaces the world on",13
        !pet " the cartridge. (Y/N) ",0
tx_go:  jsr yn_key
        cmp #"Y"
        bne +
        jmp tx_copy
+       jmp redraw

;;; the tapecart's tclib (eftc.s) to TCX_ORG, the cart into command mode, and
;;; its collection's save layout checked (asm/boot.s: "UCFG" and LAYOUT in
;;; its settings page): C clear; C set, said why, if it is not there or not
;;; a collection this build knows the log of.  On the EasyFlash after.
tx_open:
        jsr pr
        !pet 13," The tapecart",0
        ldx #rd_tcx + 6 - rd_rows
        jsr rd7
        jsr TCX_ORG             ; (tx_open there)
        bcc +
        jsr pr
        !pet ": none answers.",0
        sec
        rts
+       jsr dev_tc
        ldx #rd_set + 6 - rd_rows
        jsr rd7
        jsr dev_ef
        ldx #$03
-       lda DBUF,x
        cmp ucfg,x
        bne +
        dex
        bpl -
        lda DBUF+TP_SET_LAYOUT
        cmp #TP_LAYOUT
        bne +
        lda #"."
        jsr CHROUT
        clc
        rts
+       jsr pr
        !pet " has no Ultima collection",13
        !pet " whose saves this cartridge knows: give",13
        !pet " it the collection's latest build.",0
        sec
        rts

;;; the source's log: C clear and tx_dir its directory if it has a saved
;;; game (the save area's S12 and S13, as i_u6 asks), C set if not.  Ends
;;; on the EasyFlash.
tx_find:
        lda tx_src
        jsr tx_dev
        lda #$00
        sta tx_has
        jsr u6_find_log
        bcs tf_no
        ldx #$04
-       lda ep,x                ; address and count, adjacent
        sta tx_dir,x
        dex
        bpl -
        inc tx_has
        lda #12
        sta x6_sec
        jsr x6_seckey
        jsr tx_lookup
        bcs tf_no
        inc x6_sec
        jsr x6_seckey
        jsr tx_lookup
tf_no:  jsr dev_ef
        rts

;;; the copy, tx_src's log into tx_dst's other half
tx_copy:
        lda tx_dst
        jsr tx_dev
        jsr x6_begin            ; its other half, erased; x6_uselog = 0
        lda #$00
        sta x6_disk
tx_disk:
        jsr x6_setdisk          ; (its tables: no drive)
tx_file:
        lda x6_left
        bne +
        jmp tx_save
+       jsr x6_name
        jsr dot
        lda tx_src
        jsr tx_dev
        jsr tx_lookup           ; the source's newest, as its log holds it:
        bcs tx_fnext            ; sectors with their links (x6_content's rule)
        lda reply+5
        and #F6_LINKS
        beq tx_fnext
        lda reply+3
        beq tx_fnext
        cmp #MAXSEC+1
        bcs tx_fnext
        sta x6_n
        ldx #$02
-       lda reply,x
        sta tc_addr,x
        dex
        bpl -
        lda #>BUF
        ldx x6_n
        jsr fread_to
        jsr dev_ef              ; the original, from here, into ORIG
        lda #>ORIG
        sta x6_dpage
        jsr x6_content
        bcc +
        jmp x6_missing
+       jsr x6_same
        bcc tx_fnext            ; the original: nothing to log
        lda tx_dst
        jsr tx_dev
        jsr x6_logfile
tx_fnext:
        dec x6_left
        jmp tx_file
tx_save:
        lda x6_disk             ; the save area: 1A only
        bne tx_dnext
        lda #9
        sta x6_sec
ts_sec: jsr x6_seckey
        lda tx_src
        jsr tx_dev
        jsr tx_lookup
        bcs ts_next
        ldx #$02
-       lda reply,x
        sta tc_addr,x
        dex
        bpl -
        lda #>DBUF
        ldx #$01
        jsr fread_to
        jsr dev_ef              ; the original, into ORIG
        jsr x6_origsec
        lda #>ORIG
        ldx #$01
        jsr fread_to
        ldy #$00
-       lda DBUF,y
        cmp ORIG,y
        bne +
        iny
        bne -
        beq ts_next             ; the same
+       lda tx_dst
        jsr tx_dev
        lda #>DBUF
        ldx #$01
        jsr x6_logpages
        lda #$00
        sta x6_n
        jsr x6_entry
ts_next:
        inc x6_sec
        lda x6_sec
        cmp #21
        bne ts_sec
tx_dnext:
        inc x6_disk
        lda x6_disk
        cmp #$02
        beq +
        jmp tx_disk
+       lda tx_dst
        jsr tx_dev
        jsr x6_commit           ; the header; the old half erased
        jmp x_done2

;;; DIR_LOOKUP lkey in the source's log (on the source): C clear and reply,
;;; or C set
tx_lookup:
        lda tx_has
        bne +
        sec
        rts
+       ldx #$04
-       lda tx_dir,x
        sta dparm,x
        dex
        bpl -
        jmp dlookup

;;; tc_read by the row whose last byte is rd_rows + X: tc_addr, tc_len,
;;; tc_dest, on the cart el_dev says
rd7:    ldy #6
-       lda rd_rows,x
        sta tc_addr,y
        dex
        dey
        bpl -
        jmp tc_read
rd_rows:
rd_font: !byte <FONT_SRC, >FONT_SRC, ^FONT_SRC, <$0800, >$0800, <CHARS, >CHARS
rd_efi:  !byte <EFI_SRC, >EFI_SRC, ^EFI_SRC, <EFI_LEN, >EFI_LEN, $00, $10   ; efinit.s, to $1000
rd_tcx:  !byte <TCX_SRC, >TCX_SRC, ^TCX_SRC, <TCX_LEN, >TCX_LEN, <TCX_ORG, >TCX_ORG
rd_set:  !byte <TP_SETTINGS, >TP_SETTINGS, ^TP_SETTINGS, 16, 0, <DBUF, >DBUF
!ifdef U5L_SRC {
rd_u5:   !byte <U5L_SRC, >U5L_SRC, ^U5L_SRC, <U5L_LEN, >U5L_LEN, <U5L_ORG, >U5L_ORG

;;; ---- 5: Ultima V from the tapecart, its music from here (efu5.s) ---------
u5_go:  jsr p_area
        jsr tx_open
        bcs +
        ldx #rd_u5 + 6 - rd_rows
        jsr rd7
        jsr U5L_ORG             ; (back only when it refuses, said why)
+       jmp x_key
}

;;; the tc_* names, and the log's place (u6_tops here, page_u6x.s's
;;; u6_bases), on the cart A says: bit 7 the tapecart, else the EasyFlash
tx_dev: asl
        bcs dev_tc
dev_ef: lda #$00
        sta el_dev
        ldx #$05
-       lda ef_tops,x
        sta u6_tops,x
        lda ef_bases,x
        sta u6_bases,x
        dex
        bpl -
        rts
dev_tc: lda #$80
        sta el_dev
        ldx #$05
-       lda tp_tops,x
        sta u6_tops,x
        lda tp_bases,x
        sta u6_bases,x
        dex
        bpl -
        rts

;;; ==================================================================
;;; what the transfer code takes from page.s
;;; ==================================================================

;;; the log's active half, by efinit.s's rules: C clear, act = 0 or 3, gen
;;; its generation, ep/dcount its directory (the newest entry, the count);
;;; C set if neither half has a header
u6_find_log:
        ldx #$00
        jsr fl_top
        sta ok0
        lda tgen
        sta gen0
        lda tgen+1
        sta gen0+1
        ldx #$03
        jsr fl_top
        beq fl_h0               ; half 1 invalid: half 0 (if that is)
        lda ok0
        beq fl_h1
        lda tgen+1              ; both: half 1 if its generation is higher
        cmp gen0+1
        bcc fl_h0
        bne fl_h1
        lda gen0
        cmp tgen
        bcs fl_h0
fl_h1:  lda tgen
        sta gen
        lda tgen+1
        sta gen+1
        ldx #$03
        bne fl_scan
fl_h0:  lda ok0
        bne +
        sec
        rts
+       lda gen0
        sta gen
        lda gen0+1
        sta gen+1
        ldx #$00
fl_scan:
        stx act
        lda u6_tops,x
        sta ep
        lda u6_tops+1,x
        sta ep+1
        lda u6_tops+2,x
        sta ep+2
        lda #$00
        sta dcount
        sta dcount+1
fs_loop:
        sec                     ; the slot below: a key byte, or $FF
        lda ep
        sbc #ENTRY
        sta tc_addr
        lda ep+1
        sbc #$00
        sta tc_addr+1
        lda ep+2
        sbc #$00
        sta tc_addr+2
        lda #<probe
        sta tc_dest
        lda #>probe
        sta tc_dest+1
        lda #$01
        sta tc_len
        lda #$00
        sta tc_len+1
        jsr tc_read
        lda probe
        cmp #$ff
        beq +
        ldx #$02
-       lda tc_addr,x
        sta ep,x
        dex
        bpl -
        inc dcount
        bne fs_loop
        inc dcount+1
        jmp fs_loop
+       clc
        rts

;;; half X's top slot into ent: A = 1 (Z clear) if it is a header, tgen its
;;; generation
fl_top: lda #$00
        sta tgen
        sta tgen+1
        sec
        lda u6_tops,x
        sbc #ENTRY
        sta tc_addr
        lda u6_tops+1,x
        sbc #$00
        sta tc_addr+1
        lda u6_tops+2,x
        sbc #$00
        sta tc_addr+2
        lda #<ent
        sta tc_dest
        lda #>ent
        sta tc_dest+1
        lda #ENTRY
        sta tc_len
        lda #$00
        sta tc_len+1
        jsr tc_read
        bit el_dev
        bmi ft_tc
        ldx #ENTRY-1
-       lda ent,x
        cmp hdr,x
        beq +
        cpx #KEYLEN             ; (the generation and its complement)
        bcc ft_bad
        cpx #KEYLEN+4
        bcs ft_bad
+       dex
        bpl -
ft_gen: lda ent+KEYLEN
        eor #$ff
        cmp ent+KEYLEN+2
        bne ft_bad
        lda ent+KEYLEN+1
        eor #$ff
        cmp ent+KEYLEN+3
        bne ft_bad
        lda ent+KEYLEN
        sta tgen
        lda ent+KEYLEN+1
        sta tgen+1
        lda #$01
        rts
ft_bad: lda #$00
        rts
;;; the tapecart's rule (asm/page.s u6_top, init_u6.s): erased is invalid, a
;;; header is checked by its name and complement, and an ordinary entry is
;;; a half from before headers -- generation 0
ft_tc:  lda ent
        cmp #$ff
        beq ft_bad
        cmp #$fe
        beq +
        lda #$01
        rts
+       ldx #$02
-       lda ent+1,x
        cmp log_name,x
        bne ft_bad
        dex
        bpl -
        bmi ft_gen

;;; the saved game's party (page.s i_u6): has_save set, and a line per
;;; member -- name, hit points and their maximum -- if the log has the save
;;; area's S12 and S13 (a world reset, or one never saved, has not: the
;;; game's own menu then says "Create a Character first")
i_u6:   lda #$00
        sta has_save
        jsr u6_find_log
        bcc +
        rts
+       lda #$0c                ; S12 into BUF, S13 into BUF+$100
        ldx #>BUF
        jsr u6_sector
        bcs i6_out
        lda #$0d
        ldx #>(BUF+$100)
        jsr u6_sector
        bcs i6_out
        inc has_save
        lda BUF+$18c            ; six members at most ($588D-$5892)
        cmp #$06
        bcs i6_out
        sta count
        inc count
        lda #$00
        sta seat
i6_next:
        ldx seat                ; the member's actor number, and its slot
        lda BUF+$18d,x
        ldy #14
-       cmp BUF+$6e,y
        beq +
        dey
        bpl -
        jmp i6_skip             ; not a named character
+       sty rec
        lda BUF+$7d,y           ; its name
        sta ptr
        lda #>BUF
        sta ptr+1
        jsr pr
        !pet "   ",0
        lda #13
        jsr prname
        jsr pr
        !pet "HP ",0
        lda #3                  ; a byte, right-aligned (page.s)
        sta nwid
        ldy rec
        lda BUF+$e8,y
        ldx #$00
        jsr prdec16
        lda #"/"
        jsr CHROUT
        ldy rec
        lda BUF+$ff,y           ; slot 0 at S12 +$FF, 1-14 at S13 +0..
        ldx #$00
        jsr prdec16
        lda #13
        jsr CHROUT
i6_skip:
        inc seat
        dec count
        bne i6_next
i6_out: rts

;;; 1A T6 S(A)'s newest version, the log's, into page X; C set if the log
;;; has none (page.s u6_sector)
u6_sector:
        sta skey+3
        stx dpage
        jsr tc_enter
        lda #CMD_DIR_SETPARAMS
        jsr tc_sendbyte
        ldy #$00
-       lda ep,y                ; address (3) and count (2), adjacent
        jsr tc_sendbyte
        iny
        cpy #$05
        bne -
        lda #KEYLEN
        jsr tc_sendbyte
        lda #DATALEN
        jsr tc_sendbyte
        lda #CMD_DIR_LOOKUP
        jsr tc_sendbyte
        ldy #$00
-       lda skey,y
        jsr tc_sendbyte
        iny
        cpy #KEYLEN
        bne -
        jsr tc_getbyte
        bne us_miss
        ldy #$00
-       jsr tc_getbyte
        sta reply,y
        iny
        cpy #DATALEN
        bne -
        jsr tc_leave
        lda reply
        sta tc_addr
        lda reply+1
        sta tc_addr+1
        lda reply+2
        sta tc_addr+2
        lda dpage
        ldx #$01
        jsr fread_to
        clc
        rts
us_miss:
        jsr tc_leave
        sec
        rts


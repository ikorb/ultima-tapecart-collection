        sta ptr2
        pla
        sta ptr2+1
-       inc ptr2
        bne +
        inc ptr2+1
+       ldy #$00
        lda (ptr2),y
        beq +
        jsr CHROUT
        jmp -
+       lda ptr2+1
        pha
        lda ptr2
        pha
        rts


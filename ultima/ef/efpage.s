;;; the page at tc_dest to tc_addr; both step on by a page
write_page:
        lda #$00
        sta tc_len
        lda #$01
        sta tc_len+1
        lda tc_dest+1
        pha
        jsr tc_write
        pla
        sta tc_dest+1
        inc tc_dest+1
        inc tc_addr+1
        bne +
        inc tc_addr+2
+       rts

dot:    lda #"."
        jmp CHROUT


#!/usr/bin/env python3
"""Build the complete Ultima Tapecart Collection cartridge.

    python -m ultima.build [ultima-collection.tcrt]

Produces the full image and the update image (which stops below the saves).
The tapecart's own loader fastloads the first stage, which loads the
launcher -- font, per-game page and menu -- whose menu lists the games;
picking one opens its page, and launching it scatter-loads it out of flash
and jumps to its init stub.

Flash map (ultima/flash/regions.py):
    $000000  game list for the menu, $0000F8 the launcher's locator
    $000100  one descriptor page per game, $000700 the C128 page
    $000800  the first stage (2 KiB)
    $001000  the launcher's PRG
    $007F00  Akalabeth's descriptor page (regions.desc_offset)
    $008000+ per-game data; the save regions at fixed addresses at the top
"""
import importlib.util
import os
import re
import subprocess
import sys
from pathlib import Path

from ultima import paths


from ultima.flash.layout import image_from
from ultima.flash.tcrt import TCRT
from ultima.launcher import launcher
from ultima.launcher import logo
from ultima.flash import regions

BUILD = paths.BUILD
# the menu's list, in order: a game's place in it is its key, 0-6
GAMES = ["u0", "u1", "u2", "u3", "u4", "u5", "u6"]


# The build's debug switches, and what the banner calls each when it is set:
# an image built with one is for the emulator, never for a cart.
DEBUG_SWITCHES = {"U5_SAVE_FROM": "U5 seed", "U5_NO_FAST": "slow", "U1_NO_FAST": "U1 slow"}


def debug_switches():
    return [name for var, name in DEBUG_SWITCHES.items() if os.environ.get(var)]


def version():
    """The release's number: the Makefile's VERSION (exported to its
    recipes), or read from the Makefile when run by hand."""
    v = os.environ.get("VERSION")
    if not v:
        m = re.search(r"^VERSION\s*=\s*(\S+)", Path(os.path.join(paths.ROOT, "Makefile")).read_text(), re.M)
        v = m.group(1)
    return v


def banner_fragment(switches, ver=None):
    """What asm/menu.s includes for its banner: "Version x" -- no date, so
    that two builds from the same inputs are the same file -- then a second
    line: empty, or, in red, that this is a debug build and which switches
    made it.  Two lines either way: the menu lays out its rows for two
    (banner 13-14, games 16-22, prompt 24)."""
    first = f"    Version {ver or version()}"
    second = ('13' if not switches else
              '13,28,"    DEBUG, do not flash: ' + ", ".join(switches) + '",5')
    for text in (first, second.split('"')[1] if '"' in second else ""):
        assert len(text) < 40, f"a banner line is {len(text)} characters"
    return f'        !pet GREY,"{first}",{second}\n'


def write_banner():
    """Generate the fragment asm/menu.s includes for its banner."""
    os.makedirs(BUILD, exist_ok=True)
    with open(os.path.join(BUILD, "banner.s"), "w") as fh:
        fh.write(banner_fragment(debug_switches()))


def load_game(name):
    return importlib.import_module(f"ultima.games.{name}.build")


def symbol(symfile, name):
    pat = re.compile(r"^\s*" + re.escape(name) + r"\s*=\s*\$([0-9a-fA-F]+)")
    for line in Path(symfile).read_text().splitlines():
        m = pat.match(line)
        if m:
            return int(m.group(1), 16)
    raise SystemExit(f"symbol {name!r} not found in {symfile}")


def petscii(text, length):
    """A game's name as the launcher shows it -- "Ultima IV", from the
    build's "ULTIMA IV" -- in mixed-case PETSCII (launcher.display), padded
    with NULs."""
    words = [w if set(w) <= set("IVX") else w.capitalize() for w in text.split(" ")]
    out = launcher.display(" ".join(words))[:length]
    return out + b"\x00" * (length - len(out))


def first_stage():
    """asm/boot.s assembled with the flash map's numbers, as a PRG padded to
    regions.BOOT_LEN: what the loadinfo loads."""
    games = sorted(regions.JOURNAL, key=regions.DESC_INDEX.get)
    with open(os.path.join(BUILD, "boot_tab.s"), "w") as fh:
        fh.write(";;; generated by ultima/build.py: the journals (regions.journal),\n"
                 ";;; and the save region each one's slot must lie in\n")
        fh.write(f"JOURNALS = {len(games)}\n")
        for key, pick in (("jn_mid", lambda g: regions.journal(g)[0] >> 8 & 0xFF),
                          ("jn_hi", lambda g: regions.journal(g)[0] >> 16),
                          ("jn_blocks", lambda g: regions.journal(g)[1] // regions.ERASE_BLOCK),
                          ("jn_lo_mid", lambda g: regions.save_region(g)[0] >> 8 & 0xFF),
                          ("jn_lo_hi", lambda g: regions.save_region(g)[0] >> 16)):
            fh.write(f"{key}: !byte " + ", ".join(f"${pick(g):02x}" for g in games) + "\n")
    out = os.path.join(BUILD, "boot.prg")
    defs = {"BOOT_ORG": regions.BOOT_ORG, "BOOT_LEN": regions.BOOT_LEN,
            "LAUNCHER_LOC": regions.LAUNCHER_LOC, "FONT_ORG": launcher.FONT_ORG,
            "MENU_ORG": launcher.MENU_ORG, "SETTINGS": regions.SETTINGS,
            "SET_LAYOUT": regions.SET_LAYOUT, "LAYOUT": regions.LAYOUT}
    subprocess.run(["acme", "-f", "cbm", "-I", paths.ASM, "-I", BUILD,
                    *[f"-D{k}={v}" for k, v in defs.items()],
                    "-o", out, "-l", os.path.join(BUILD, "boot.sym"),
                    os.path.join(paths.ASM, "boot.s")], check=True)
    with open(out, "rb") as fh:
        prg = fh.read()
    assert prg[:2] == regions.BOOT_ORG.to_bytes(2, "little")
    assert len(prg) <= regions.BOOT_LEN, len(prg)
    return prg.ljust(regions.BOOT_LEN, b"\x00")


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BUILD, "ultima-collection.tcrt")
    os.makedirs(BUILD, exist_ok=True)

    blobs = []
    table = bytearray([len(GAMES)])
    total_used = 0
    parts = {}

    for index, name in enumerate(GAMES):
        mod = load_game(name)
        p = parts[name] = mod.parts()
        blobs += p["blobs"]
        blobs.append((regions.desc_offset(name), p["desc"]))
        if p.get("c128"):
            blobs.append((regions.C128_DESC, p["c128"]["desc"]))
        table += petscii(p["name"], regions.MENU_NAME_LEN)
        # the descriptor's flash page: the menu reads it from $00xx00
        assert regions.desc_offset(name) < 0x10000
        table += bytes([regions.DESC_INDEX[name], regions.desc_offset(name) >> 8])
        total_used += p["used"]
        saves = f"saves to {p['save_end']:#08x}" if p["save_end"] else "no saves"
        print(f"  {p['name']:<12} {p['used'] / 1024:7.1f} KiB data, "
              f"{saves}, {p['desc'][2]} segments")

    # ---- the launcher's page: after the games, whose fresh save slots are
    # what its reset writes back
    fresh = image_from(blobs, regions.FLASH_SIZE)
    lblobs, page, _runs, font = launcher.build(parts, fresh)
    blobs += lblobs
    print(f"  {'launcher':<12} {sum(len(b) for _o, b in lblobs) / 1024:7.1f} KiB: every game's "
          f"fresh saves (the page, {len(page)} bytes, is in the menu's PRG)")
    assert len(table) <= 128, f"game list is {len(table)} bytes, menu reads 128"
    blobs.append((regions.MENU_TABLE, bytes(table)))

    # ---- the menu itself -------------------------------------------------
    menu_prg = os.path.join(BUILD, "menu.prg")
    menu_sym = os.path.join(BUILD, "menu.sym")
    # The banner carries the version (the Makefile's), and says when a debug
    # switch made the image.
    write_banner()
    with open(os.path.join(BUILD, "logo.s"), "w") as fh:
        fh.write(logo.source(logo.build()))
    subprocess.run(["acme", "-f", "cbm", "-I", paths.ASM,
                    "-I", BUILD,
                    "-o", menu_prg, "-l", menu_sym,
                    os.path.join(paths.ASM, "menu.s")], check=True)

    with open(menu_prg, "rb") as fh:
        menu_only = fh.read()
    # The first stage loads one PRG: the font, the page, the menu, U6's REU
    # line, the page's export tables up to $A000 and the page's second piece
    # after them -- so the menu has nothing to load when a game is picked.
    # The gaps between are filler.  Only the menu has to be clear of every
    # game's segments (test_collection); the rest is done with by then.
    assert menu_only[:2] == bytes([launcher.MENU_ORG & 0xFF, launcher.MENU_ORG >> 8])
    body = bytearray(font).ljust(launcher.PAGE_ORG - launcher.FONT_ORG, b"\x00") + page
    body = body.ljust(launcher.MENU_ORG - launcher.FONT_ORG, b"\x00") + menu_only[2:]
    # then the page's export tables, after the menu (launcher.py XDATA)
    xdata = launcher.symbols()["XDATA"]
    if launcher.FONT_ORG + len(body) > xdata:
        raise SystemExit(f"the menu runs into the page's export tables at {xdata:#06x}")
    # Ultima VI's REU line, the page before them (launcher.py REU_ORG)
    reu_org = launcher.symbols()["REU_ORG"]
    if launcher.FONT_ORG + len(body) > reu_org:
        raise SystemExit(f"the menu runs into the page's REU line at {reu_org:#06x}")
    with open(os.path.join(BUILD, "page_reu.bin"), "rb") as fh:
        body = body.ljust(reu_org - launcher.FONT_ORG, b"\x00") + fh.read()
    assert launcher.FONT_ORG + len(body) <= xdata
    with open(os.path.join(BUILD, "xdata.bin"), "rb") as fh:
        body = body.ljust(xdata - launcher.FONT_ORG, b"\x00") + fh.read()
    assert launcher.FONT_ORG + len(body) <= launcher.XDATA_END
    with open(os.path.join(BUILD, "page_hi.bin"), "rb") as fh:     # page.s page_hi
        body = body.ljust(launcher.XDATA_END - launcher.FONT_ORG, b"\x00") + fh.read()
    menu = bytes([launcher.FONT_ORG & 0xFF, launcher.FONT_ORG >> 8]) + bytes(body)
    if regions.MENU_PRG + len(menu) > regions.MENU_PRG_END:
        raise SystemExit(f"the menu is {len(menu)} bytes and runs into the "
                         f"descriptors at {regions.MENU_PRG_END:#08x}")
    blobs.append((regions.MENU_PRG, menu))
    # where the first stage finds it
    blobs.append((regions.LAUNCHER_LOC, regions.MENU_PRG.to_bytes(3, "little")
                  + len(menu).to_bytes(2, "little")))
    boot = first_stage()
    blobs.append((regions.BOOT_PRG, boot))
    # the settings page as a fresh cart has it: the magic, every option off,
    # and the save layout's stamp (asm/boot.s checks it)
    settings = bytearray(256)
    settings[:4] = regions.SET_MAGIC
    settings[regions.SET_LAYOUT] = regions.LAYOUT
    blobs.append((regions.SETTINGS, bytes(settings)))
    start = symbol(menu_sym, "start")
    if symbol(menu_sym, "menu_end") > reu_org:
        raise SystemExit(f"the menu runs into the page's REU line at {reu_org:#06x}")

    size = max(o + len(b) for o, b in blobs)
    size = (size + regions.ERASE_BLOCK - 1) // regions.ERASE_BLOCK * regions.ERASE_BLOCK
    flash = image_from(blobs, size)

    # The loadinfo: the first stage, always BOOT_LEN bytes from BOOT_PRG,
    # called at its origin.  An update image cannot change the loadinfo, and
    # with these three fixed it never has to: the first stage loads the
    # launcher at whatever length this build gave it, and starts it at the
    # menu's origin, a JMP to start.
    org = launcher.MENU_ORG
    o = org - launcher.FONT_ORG + 2
    if menu[o:o + 3] != bytes([0x4C, start & 0xFF, start >> 8]):
        raise SystemExit("the menu no longer starts with JMP start")
    img = TCRT(data_address=regions.BOOT_PRG,
               data_length=regions.BOOT_LEN,
               call_address=regions.BOOT_ORG,
               filename="ULTIMACOLLECTION",
               flash=flash)
    img.write(out, trim=False)

    # The update image: everything below the save area, as a raw file for
    # the flash tool's "Write data file" at offset 0, which erases only the
    # blocks it writes -- so the saves at the top of flash survive.
    # It stops at the end of the game data, not at the save area: nothing
    # uses the gap between, so writing $FF over it would only be slower.
    update = os.path.splitext(out)[0] + "-update.bin"
    data_end = max(o + len(b) for o, b in blobs if o < regions.SAVE_AREA)
    data_end = (data_end + regions.ERASE_BLOCK - 1) // regions.ERASE_BLOCK * regions.ERASE_BLOCK
    assert data_end <= regions.SAVE_AREA
    with open(update, "wb") as fh:
        fh.write(flash[:data_end])

    print(f"\n{out}")
    print(f"  first stage: {regions.BOOT_LEN} bytes at {regions.BOOT_PRG:#08x}, "
          f"{len(boot.rstrip(bytes(1)))} used, runs at ${regions.BOOT_ORG:04x}")
    print(f"  menu: {len(menu)} bytes at {regions.MENU_PRG:#08x}, "
          f"loads to ${menu[0] | menu[1] << 8:04x}, starts at ${start:04x}")
    print(f"  image: {regions.DATA_END / 1024:.1f} KiB of game data, saves from "
          f"{regions.SAVE_AREA:#08x} up, {regions.free() / 1024:.0f} KiB free between")
    print(f"  update image (keeps the saves): {update}, {data_end / 1024:.0f} KiB, "
          f"flash with Write data file at offset 0")
    if debug_switches():
        print(f"\n  *** DEBUG BUILD ({', '.join(debug_switches())}): for the emulator, "
              f"not for a cart -- the banner says so ***")


if __name__ == "__main__":
    main()

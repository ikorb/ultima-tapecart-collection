"""What an init stub needs to assemble tclib's tc_init (asm/tcinit.s) for a
driver built with TC_INIT_ELSEWHERE: the driver's tc_v_*/tc_d_* operands,
tclib's port bits and the options it was built with, from its symbol file."""
import re
from pathlib import Path

WANT = re.compile(r"^(tc_v_\w+|tc_d_\w+|BIT_MOTOR|BIT_SENSE|BIT_WRITE|TC_KEEP_01|TC_IO_01|"
                  r"TC_FAST2|TC_GUARD)$")


def tcinit_include(symfile, out, extra=()):
    """`extra`: more of the driver's symbols the init stub uses."""
    lines = [";;; generated by tcsyms.py from " + symfile.split("/")[-1]]
    for line in Path(symfile).read_text().splitlines():
        m = re.match(r"\s*(\w+)\s*=\s*\$([0-9a-fA-F]+)", line)
        if m and (WANT.match(m.group(1)) or m.group(1) in extra):
            lines.append(f"{m.group(1)} = ${m.group(2)}")
    names = {l.split()[0] for l in lines[1:]}
    assert {"tc_v_base", "tc_d_norm", "BIT_MOTOR", "TC_KEEP_01", *extra} <= names, names
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")

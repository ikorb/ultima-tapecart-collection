#!/usr/bin/env python3
"""The save editor's game data, generated from your disks (the stand-ins in
build/disks, `make disks`) -- none of it is in the repository:

  editor/src/games/u6names.ts     Ultima VI's object names (1A track 35,
                                  sectors 0-9, 16 bytes each, singular forms),
                                  NPC names (byte 1 and the name of each
                                  conversation file on 2A, 2B, 3A) and the
                                  object types that stack (`game`'s table at
                                  $34C6, which $34B5 searches)
  editor/src/games/u6original.ts  Ultima VI's save area as the Surface disk
                                  ships it (1A track 6, sectors 9-20): a
                                  launcher save file holds only the sectors
                                  that differ from it

    python3 editor/gen_data.py          (make editor and make editor-test run it)
"""
import base64
import json
import os
import re
import sys
from pathlib import Path

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from ultima import paths                        # noqa: E402
from ultima.disks.d64 import D64                # noqa: E402

OUT = os.path.join(REPO, "editor", "src", "games")
HEADER = "// Generated by editor/gen_data.py from your disks -- do not edit, not in the repository.\n"


def text(b):
    """Screen codes 1-26 as lower case, the rest as they are."""
    return "".join(chr(c + 0x60) if 1 <= c <= 26 else chr(c) for c in b)


def objects():
    d = D64(paths.disk("u6-1a"))
    table = b"".join(bytes(d.sector(35, k)) for k in range(10))
    names = []
    for k in range(len(table) // 16):
        e = table[16 * k:16 * k + 16]
        z = e.find(0)
        s = text(e[:16 if z < 0 else z])
        s = re.sub(r"/([^\\]*)\\\S*", r"\1", s)        # "/x\y" keeps x
        names.append(re.sub(r"\\\S*", "", s))            # "\y" drops y
    while names and not names[-1].strip():
        names.pop()
    return names


def npcs():
    seen = {}
    for key in ("u6-2a", "u6-2b", "u6-3a"):
        d = D64(paths.disk(key))
        for name, _type, _t, _s, _blocks in d.directory():
            data, _ok = d.file(name)
            data = bytes(data)
            if data[:1] != b"\xff":
                continue
            seen[data[1]] = text(data[2:data.index(0xF1)])
    names = [""] * (max(seen) + 1)
    for n, s in seen.items():
        names[n] = s
    return names


def stacks():
    game = bytes(D64(paths.disk("u6-3b")).file("GAME")[0])
    at = lambda a: a - 0x0200 + 2                   # GAME loads at $0200
    assert game[at(0x34B5):at(0x34B5) + 2] == bytes([0xA2, 0x1D]), "game $34B5 is not LDX #29"
    return list(game[at(0x34C6):at(0x34C6) + 29])


def save_area():
    d = D64(paths.disk("u6-1a"))
    return b"".join(bytes(d.sector(6, s)) for s in range(9, 21))


def ts_list(name, items):
    lines, line = [], "  "
    for s in items:
        piece = json.dumps(s) + ", "
        if len(line) + len(piece) > 110:
            lines.append(line.rstrip())
            line = "  "
        line += piece
    lines.append(line.rstrip())
    return f"export const {name}: string[] = [\n" + "\n".join(lines) + "\n];\n"


def main():
    paths.require_disks(["u6-1a", "u6-2a", "u6-2b", "u6-3a"])
    names = (HEADER + "\n" + ts_list("OBJECTS", objects()) + "\n" + ts_list("NPCS", npcs())
             + "\nexport const STACKS: number[] = [" + ", ".join(f"0x{v:02x}" for v in stacks()) + "];\n")
    b64 = base64.b64encode(save_area()).decode()
    chunks = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    original = (HEADER + "\nexport const ORIGINAL_SAVE_AREA = Uint8Array.from(atob(\n"
                + " +\n".join(f'  "{c}"' for c in chunks)
                + "\n), c => c.charCodeAt(0));\n")
    for fname, body in (("u6names.ts", names), ("u6original.ts", original)):
        path = os.path.join(OUT, fname)
        if not os.path.exists(path) or Path(path).read_text() != body:
            Path(path).write_text(body)


if __name__ == "__main__":
    main()

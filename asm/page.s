;;; the zero-terminated string after the JSR
pr:     pla
        sta ptr2
        pla
        sta ptr2+1
-       inc ptr2
        bne +
        inc ptr2+1
+       ldy #$00
        lda (ptr2),y
        beq +
        jsr CHROUT
        jmp -
+       lda ptr2+1
        pha
        lda ptr2
        pha
        rts

getkey: jsr SCNKEY
        jsr GETIN
        beq getkey
        rts

;;; A = "Y" or "N", and nothing else counts: a key that bounces (the one
;;; that brought the question up, seen again) must not answer it.  RUN/STOP
;;; and <- are N.
yn_key: jsr getkey
        cmp #"Y"
        beq ++
        cmp #"N"
        beq ++
        cmp #$03                ; RUN/STOP
        beq +
        cmp #$5f                ; <-
        bne yn_key
+       lda #"N"
++      rts


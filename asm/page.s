;;; page.s -- the launcher's per-game page.
;;;
;;; It comes in with the menu (menu.s, one PRG from $4800) and the menu calls
;;; it when a game is picked, before any of that game is loaded: so nothing
;;; here has to fit around a game.  Two pieces: from $5000 to the menu at
;;; $8700, and from $A000 (page_hi, at the end of this file), after the
;;; export tables, under BASIC's ROM, which the menu banks out while the
;;; page runs.  It shows the saved game, offers the game's options, resets
;;; the save, and returns:
;;;
;;;   in:  A = the game (its descriptor index: u1 u3 u2 u4 u5 u6 u0)
;;;        X/Y = its 16-byte name in the menu's game list
;;;        or A = $87-$89: the page of Ultima VII-IX, which are not here
;;;   out: C set    back: A = $FF the game list, or 0-6 the page of the
;;;                 game at that place in the list (its key, 0-6, here)
;;;        C clear  launch it; X/Y = a poke list the menu applies after the
;;;                 game's segments are loaded and before its init stub runs:
;;;                 a count, then that many (address lo, hi, value)
;;;
;;; The menu holds the cart in command mode, so this tclib copy is built
;;; without tc_cmdmode.  Interrupts are off (the menu's), so the keyboard is
;;; scanned by hand, as the menu does.
;;;
;;; What is game-specific is data: build/page_data.s, generated by
;;; ultima/build.py from each game's build -- the slot addresses the info
;;; routines read, which options a game's driver supports and where its
;;; options byte is, and the reset tables (every erase block of the game's
;;; save region, and the fresh contents to write back, zx02-crunched).

PAGE_ORG = $5000                ; after the font; the menu is at $8700
BUF      = $0800                ; flash data, staging; up to $3FFF (the
                                ; screen is at $4400)

CHROUT = $ffd2
SCNKEY = $ff9f
GETIN  = $ffe4
PLOT   = $fff0

ptr  = $fb                      ; free for the user under the KERNAL
ptr2 = $fd

CAP_FOOD = %00000001            ; the driver can turn food use while walking off
                                ; (Akalabeth: a poke, as all its options)
CAP_PASS = %00000010            ; ... and the pass on an idle keyboard
CAP_TORCH = %00010000           ; ... and a torch used up when lit
OPT_FOOD = %00000001            ; options byte: set = food use OFF
OPT_PASS = %00000010            ;               set = idle pass OFF
OPT_TORCH = %00010000           ;               set = torches never used up
CAP_TILES = %00001000           ; Ultima IV: Remastered's tiles and creation (set = on)
CAP_ITEMS = %00100000           ; spells, keys, gems (U3: powder) never used up;
                                ; Akalabeth: gold not spent (a poke, its key G)
CAP_AVOID = %01000000           ; Ultima III and IV: an attack can be avoided;
                                ; Akalabeth: always hit, always kill (a poke)
CAP_BALLOON = %10000000         ; Ultima IV: the balloon steered, no wind drift;
                                ; U2: counts stop at 99 and 9999 (a poke); U1:
                                ; no one steals; Akalabeth: invincible (a poke)
                                ; -- its line has the game's own words and key
CAP_POWERS = %00000100          ; U4: T teleports, B brings a transport, X wins a
                                ; fight; U3: Gold's trainer keys; U1 and U2: F1
                                ; tells where the party is, F7 teleports, B brings
                                ; a transport (all a poke); U5: F7
                                ; teleports, B brings a vehicle (a bit of its
                                ; options byte)
OPT_ITEMS = CAP_ITEMS           ; options byte: set = the cheat on
OPT_AVOID = CAP_AVOID
OPT_BALLOON = CAP_BALLOON

G_U1 = 0                        ; descriptor indices (regions.DESC_INDEX)
G_U3 = 1
G_U2 = 2
G_U4 = 3
G_U5 = 4
G_U6 = 5
G_U0 = 6                        ; Akalabeth: no saves, its options all pokes

KEYLEN  = 12                    ; U6's write log (ultima/games/u6/u6.inc)
DATALEN = 8
ENTRY   = KEYLEN + DATALEN
POKES   = 12                    ; the menu takes this many (menu.s POKES_MAX)
WHITE   = 5                     ; the page's two brightnesses: the keys (and the
GREY    = 155                   ; game's name) white, the rest light grey

TC_NO_CMDMODE = 1               ; the menu entered it and holds it
TC_NO_FAST    = 1

        * = PAGE_ORG
        jmp page_main

TCLIB_ORG = *
!source "tclib.s"
!source "zxdecr.s"
!source "page_data.s"           ; generated
!source "page_xfer.s"
!source "page_u2l.s"            ; Ultima II's save log
!source "page_u6x.s"
!source "page_u6t.s"

page_main:
        cmp #$80
        bcc +
        jmp not_here
+       sta gid
        stx ptr                 ; the name, copied: the menu's list is ours
        sty ptr+1               ; to keep, but ptr is not
        ldy #15
-       lda (ptr),y
        sta tname,y
        dey
        bpl -
        jsr tc_init
        jsr load_settings
        lda #$00
        sta t_go                ; (page_u6t.s)

redraw:
        jsr draw
keys:   jsr getkey
        cmp #"0"                ; another game's page, as its key on the list
        bcc +
        cmp #"7"
        bcs ++
        sbc #$2f                ; "0" (C clear: minus one more)
        sec
        rts
++      cmp #$3a                ; 7-9 ("9" + 1): a game that is not here
        bcs +
        jmp not_here
+       cmp #"B"
        beq back
        cmp #$5f                ; <-
        beq back
        cmp #$03                ; RUN/STOP
        bne +
back:   lda #$ff                ; the game list
        sec
        rts
+       ldx gid                 ; not_here's page: no more keys
        bpl +
        jmp keys
+       cmp #"L"
        bne +
        jmp launch
+       cmp #"R"
        bne +
        jsr has_rs              ; a game with saves
        bne k_rs
        jmp keys
k_rs:   jmp ask_reset
+       cmp #"F"
        bne +
        lda #CAP_FOOD
        jmp toggle
+       cmp #"P"
        bne +
        lda #CAP_PASS
        jmp toggle
+       cmp #"U"
        bne +
        lda #CAP_TORCH
        jmp toggle
+       ldx gid                 ; the items bit's key is the game's own (M;
        cmp oi_key,x            ; Akalabeth's G, for its gold) -- before G's
        bne +                   ; tiles, which Akalabeth does not have
        lda #CAP_ITEMS
        jmp toggle
+       cmp #"G"
        bne +
        lda #CAP_TILES
        jmp toggle
+       cmp #"A"
        bne +
        lda #CAP_AVOID
        jmp toggle
+       ldx gid                 ; bit 7's key is the game's own (S, W, V)
        cmp o7_key,x
        bne +
        lda #CAP_BALLOON
        jmp toggle
+       cmp #"X"
        bne +
        lda #CAP_POWERS
        jmp toggle
+       cmp #"E"
        bne +
        lda has_save            ; nothing to export: not offered
        beq kj
        jsr has_xfer
        beq kj
        jsr x_there             ; (not back here if it is not)
        jmp f_export_ask        ; (D)isks or (F)ile
+       cmp #"I"
        bne +
        jsr has_xfer
        beq kj
        jsr x_there
        jmp f_import_ask
+       cmp #"T"
        bne +
        lda u6_new              ; Ultima VI, a new Avatar
        beq kj
        jmp x6_transfer
+       cmp #"C"
        bne +
        lda gid
        cmp #G_U5
        bne kj
        jmp x_c128
+       cmp #"J"
        bne kj
        jsr has_jo              ; a game with a way in, and a saved game
        beq kj
        jmp journey
kj:     jmp keys


;;; Z clear if the game's saves can go to and from disk
has_xfer:
        ldx gid
        lda xf_hi,x
        rts

;;; Z clear if the game has saves (a reset table)
has_rs: ldx gid
        lda rs_hi,x
        rts

;;; Export and import are the end of the launcher's PRG: the export tables
;;; (launcher.py XDATA) and the page's second piece (page_file.s, below),
;;; which ends in hi_magic.  A cart given only the update image may load
;;; the launcher at an older, shorter length: then refuse, rather than run
;;; or read whatever RAM holds there.  The question's area cleared first.
x_there:
        jsr p_area
        ldx #3
-       lda hi_magic,x
        cmp xt_magic,x
        bne +
        dex
        bpl -
        rts
+       pla                     ; not back to the caller
        pla
        jsr pr
        !pet 13," The export tables are missing: this",13
        !pet " cartridge needs the full .tcrt image.",0
        jmp x_key
xt_magic: !text "UCSV"

;;; ---- the options ----------------------------------------------------
;;; A = the bit; only if the game's driver offers it
toggle: ldx gid
        and caps,x
        bne +
        jmp keys
+
        pha
        eor setbuf+4,x
        sta setbuf+4,x
        jsr save_settings
        pla
        ldx #O_COUNT-1          ; its line, rewritten
-       cmp o_bits,x
        beq +
        dex
        bne -
+       jsr o_value
        jmp keys

load_settings:
        lda #<SETTINGS
        sta tc_addr
        lda #>SETTINGS
        sta tc_addr+1
        lda #^SETTINGS
        sta tc_addr+2
        lda #>setbuf
        ldx #$01
        jsr fread_to
        ldx #$03                ; an erased (or foreign) page: all defaults
-       lda setbuf,x
        cmp magic,x
        bne +
        dex
        bpl -
        rts
+       ldx #$00
        txa
-       sta setbuf,x
        inx
        bne -
        ldx #$03
-       lda magic,x
        sta setbuf,x
        dex
        bpl -
        rts

save_settings:
        lda #<SETTINGS
        sta tc_addr
        lda #>SETTINGS
        sta tc_addr+1
        lda #^SETTINGS
        sta tc_addr+2
        jsr tc_erase_block
        lda #<setbuf
        sta tc_dest
        lda #>setbuf
        sta tc_dest+1
        jmp write_page

;;; ---- launch ---------------------------------------------------------
journey:
        lda #$01
        !byte $2c               ; BIT abs: skip the LDA
launch: lda #$00
        sta jo
        lda #$00
        sta pokes
        ldx gid
        lda opt_hi,x            ; the driver's options byte, if it has one
        beq +
        sta ptr+1
        lda opt_lo,x
        sta ptr
        lda setbuf+4,x
        and ptm,x               ; (not the options that are pokes)
        ldy jo                  ; Journey onward: the driver's own bits too
        beq ++
        ora jo_or,x
++      jsr add_poke
+       jsr opt_pokes           ; and the options that are pokes
        lda jo
        beq +
        ;; Journey onward: the game's own pokes (page_data.s, from its
        ;; build): a count, then address and value -- each game's way of
        ;; going straight to its saved game
        ldx gid
        lda jo_lo,x
        sta jr+1
        lda jo_hi,x
        sta jr+2
        ldy #$00
        jsr jr
        sta count
        cmp #$00                ; (Z was jr's INY)
        beq +
-       jsr jr
        sta ptr
        jsr jr
        sta ptr+1
        jsr jr
        jsr add_poke            ; (keeps Y)
        dec count
        bne -
+       jsr t_pokes             ; and Ultima VI's transfer, if asked for
        ldx #<pokes
        ldy #>pokes
        clc
        rts

;;; the game's option pokes (page_data.s op_*): count, then bit, address,
;;; value -- each poke whose bit the settings have on (and the game offers)
opt_pokes:
        ldx gid
        lda op_hi,x
        beq op_out
        sta opr+2
        lda op_lo,x
        sta opr+1
        ldy #$00
        jsr opr
        sta count
        cmp #$00                ; (Z was opr's INY)
        beq op_out
-       jsr opr                 ; the bit
        ldx gid
        and setbuf+4,x
        and caps,x
        sta op_on
        jsr opr
        sta ptr
        jsr opr
        sta ptr+1
        jsr opr                 ; the value
        ldx op_on
        beq +
        jsr add_poke            ; (keeps Y)
+       dec count
        bne -
op_out: rts
opr:    lda $ffff,y
        iny
        rts
op_on:  !byte 0

;;; the next byte of the Journey Onward table
jr:     lda $ffff,y
        iny
        rts

;;; Z clear if Journey onward is offered: the game has a way in, and a save
has_jo: ldx gid
        lda jo_hi,x
        beq +
        lda has_save
+       rts

;;; one (ptr, A) onto the poke list
add_poke:
        pha
        lda pokes
        asl
        adc pokes               ; x 3
        tax
        lda ptr
        sta pokes+1,x
        lda ptr+1
        sta pokes+2,x
        pla
        sta pokes+3,x
        inc pokes
        rts

;;; ---- reset ----------------------------------------------------------
ask_reset:
        jsr p_area
        jsr pr
        !pet 13," Reset the saved game to a new one?",13
        !pet " This cannot be undone. (Y/N) ",0
        jsr yn_key
        cmp #"Y"
        beq +
        jmp redraw
+       jsr pr
        !pet 13,13," Resetting",0
        jsr do_reset
        jmp redraw

;;; Erase every block of the game's save region, then write back what a
;;; fresh build puts there.  A table (page_data.s): the first block (3),
;;; the block count, the run count; then per run the flash address it goes
;;; to (3, page aligned), its page count and its sized zx02 stream (3).
do_reset:
        ldx gid
        lda rs_lo,x
        sta ptr
        lda rs_hi,x
        sta ptr+1
        ldy #$00
        lda (ptr),y
        sta tc_addr
        iny
        lda (ptr),y
        sta tc_addr+1
        iny
        lda (ptr),y
        sta tc_addr+2
        iny
        lda (ptr),y
        sta count
        iny
        lda (ptr),y
        sta runs
-       jsr tc_erase_block
        jsr dot
        lda tc_addr+1
        clc
        adc #$10
        sta tc_addr+1
        bcc +
        inc tc_addr+2
+       dec count
        bne -
        lda ptr                 ; ptr -> the first run
        clc
        adc #$05
        sta ptr
        bcc rs_run
        inc ptr+1
rs_run: lda runs
        beq rs_done
        ldy #$04                ; the stream, decoded into BUF
        lda (ptr),y
        sta tc_addr
        iny
        lda (ptr),y
        sta tc_addr+1
        iny
        lda (ptr),y
        sta tc_addr+2
        lda #<BUF
        sta tc_dest
        lda #>BUF
        sta tc_dest+1
        jsr zxd_unpack_sized
        ldy #$00                ; then written, a page at a time
        lda (ptr),y
        sta tc_addr
        iny
        lda (ptr),y
        sta tc_addr+1
        iny
        lda (ptr),y
        sta tc_addr+2
        iny
        lda (ptr),y
        sta count
        lda #<BUF
        sta tc_dest
        lda #>BUF
        sta tc_dest+1
-       jsr write_page          ; (tc_addr and tc_dest step a page)
        jsr dot
        dec count
        bne -
        lda ptr
        clc
        adc #$07
        sta ptr
        bcc +
        inc ptr+1
+       dec runs
        jmp rs_run
rs_done:
        rts

;;; the page at tc_dest to tc_addr; both step on by a page
write_page:
        lda #$00
        sta tc_len
        lda #$01
        sta tc_len+1
        lda tc_dest+1
        pha
        jsr tc_write
        pla
        sta tc_dest+1
        inc tc_dest+1
        inc tc_addr+1
        bne +
        inc tc_addr+2
+       rts

dot:    lda #"."
        jmp CHROUT

;;; ---- Ultima VII to IX ------------------------------------------------
;;; 7-9 in the list or on a page: the page of a game the cart has no room
;;; for, with only Back.  A = $87-$89 or "7"-"9".  gid is $80 + its number
;;; while it shows, and keys takes nothing but the digits and Back.
not_here:
        and #$0f
        tax
        ora #$80
        sta gid
        lda #$93
        jsr CHROUT
        jsr pr
        !pet WHITE," ",0
        lda nh_lo-7,x
        ldy nh_hi-7,x
        jsr prs
        jsr pr
        !pet GREY,13,13," This game was omitted due to limited",13
        !pet " cartridge memory.",13,13
        !pet " ",WHITE,"B",GREY,"  Back",13,0
        jmp keys
nh_lo:  !byte <nh_7, <nh_8, <nh_9
nh_hi:  !byte >nh_7, >nh_8, >nh_9
nh_7:   !pet "Ultima VII",0
nh_8:   !pet "Ultima VIII",0
nh_9:   !pet "Ultima IX",0

;;; ==================================================================
;;; the page itself
;;; ==================================================================
;;; The page fits the screen with the most any game shows -- Ultima IV's
;;; eight in the party and eight options -- and leaves the rows from the
;;; blank one before E/I free for a question (p_area): 24 rows at most,
;;; tests/test_page.py checks.  An option toggled is rewritten in place
;;; (o_value at its row, o_row), not the whole page.
draw:
        lda #$93
        jsr CHROUT
        jsr pr
        !pet WHITE," ",0                ; at the keys' column
        ldy #$00
-       lda tname,y
        beq +
        jsr CHROUT
        iny
        cpy #16
        bne -
+       jsr pr
        !pet GREY,13,13,0
        lda #$00
        sta has_save
        sta u6_new
        ldx gid
        lda info_lo,x
        sta ptr2
        lda info_hi,x
        sta ptr2+1
        jsr info_go
        lda has_save
        bne +
        jsr has_rs              ; (Akalabeth saves nothing)
        beq +
        jsr pr
        !pet "   No saved game",13,0
+       lda gid                 ; Ultima VI: the REU, if there is one
        cmp #G_U6               ; (page_reu.s, after the menu)
        bne +
        jsr REU_ORG
+       ldx gid                 ; a blank line before the options, if any
        lda caps,x              ; (and a saved game above them)
        beq +
        jsr has_rs
        beq +
        lda #13
        jsr CHROUT
+       ldx #$00
o_next: stx oi
        lda o_bits,x
        ldy gid
        and caps,y
        beq o_skip
        lda $d6                 ; (TBLX, the cursor's row)
        sta o_row,x
        lda o_lo,x
        ldy o_hi,x
        cpx #O_POWERS           ; X's words are the game's own
        bne +
        ldx gid
        lda ox_lo,x
        ldy ox_hi,x
        jmp o_prs
+       cpx #O_BIT7             ; and bit 7's
        bne o_own
        ldx gid
        lda o7_lo,x
        ldy o7_hi,x
        jmp o_prs
o_own:  ldx gid                 ; and the others', where a game has its own
        lda ow_hi,x             ; (ow_*: a word per option, 0 the default)
        beq ++
        sta ptr2+1
        lda ow_lo,x
        sta ptr2
        lda oi
        asl
        tay
        iny
        lda (ptr2),y
        beq ++
        pha
        dey
        lda (ptr2),y
        tax
        pla
        tay
        txa
        jmp o_prs
++      ldx oi                  ; none for this one: the default again
        lda o_lo,x
        ldy o_hi,x
o_prs:  jsr prs
        ldx oi
        jsr o_value
        lda #13
        jsr CHROUT
o_skip: ldx oi
        inx
        cpx #O_COUNT
        bne o_next
        ;; the commands, two to a row (the second at column 21)
        lda $d6                 ; where a question goes
        sta brow
        jsr pr
        !pet 13," ",WHITE,"L",GREY,"  Launch the game",0
        jsr has_jo
        beq +
        jsr pr
        !pet "  ",WHITE,"J",GREY,"  Journey onward",0
+       lda #13
        jsr CHROUT
        lda u6_new
        beq +
        jsr pr
        !pet " ",WHITE,"T",GREY,"  Transfer from Ultima IV or V",13,0
+       lda gid
        cmp #G_U5
        bne +
        jsr pr
        !pet " ",WHITE,"C",GREY,"  C128 launcher to disk",13,0
+       jsr has_xfer
        beq ++
        lda has_save            ; export only a saved game there is
        beq +
        jsr pr
        !pet " ",WHITE,"E",GREY,"  Export the save ",0
+       jsr pr
        !pet " ",WHITE,"I",GREY,"  Import a save",13,0
++      jsr has_rs
        beq +
        jsr pr
        !pet " ",WHITE,"R",GREY,"  Reset the save   ",WHITE,"B",GREY,"  Back",13,0
        rts
+       jsr pr
        !pet " ",WHITE,"B",GREY,"  Back",13,0
        rts

info_go:
        jmp (ptr2)

;;; Option X's value, at its place on its row: "on"/"off" (o_pol: for most,
;;; "on" is the bit clear -- the game as it was), "Remastered"/"original";
;;; each pair the same length, so either overwrites the other.
o_value:
        ldy o_row,x
        stx oi
        tya
        tax
        ldy oi
        lda o_col,y
        tay
        clc
        jsr PLOT
        ldx oi
        ldy gid
        lda setbuf+4,y
        and o_bits,x
        eor o_pol,x
        cpx #O_TILES
        beq +++
        tax
        bne +
        jsr pr
        !pet "off",0
        rts
+       jsr pr
        !pet "on ",0
        rts
+++     tax
        bne +
        jsr pr
        !pet "original  ",0
        rts
+       jsr pr
        !pet "Remastered",0
        rts

;;; print the string at A/Y (lo/hi), to its zero
prs:    sta ptr2
        sty ptr2+1
        ldy #$00
-       lda (ptr2),y
        beq +
        jsr CHROUT
        iny
        bne -
+       rts

;;; A question goes in the rows from brow on, which are cleared; the
;;; question's first CR leaves brow itself blank, as the page had it.
p_area: lda brow
        sta crow
-       ldx crow
        ldy #$00
        clc
        jsr PLOT
        ldy #39
--      lda #" "
        jsr CHROUT
        dey
        bne --
        inc crow
        lda crow
        cmp #25
        bcc -
        ldx brow
        ldy #$00
        clc
        jmp PLOT

;;; the options, in the order shown
O_BIT7   = 5
O_POWERS = 6
O_TILES  = 7
O_COUNT  = 8
o_bits: !byte CAP_FOOD, CAP_PASS, CAP_TORCH, CAP_ITEMS, CAP_AVOID, CAP_BALLOON
        !byte CAP_POWERS, CAP_TILES
o_pol:  !byte OPT_FOOD, OPT_PASS, OPT_TORCH, OPT_ITEMS, OPT_AVOID, OPT_BALLOON
        !byte 0, 0              ; X and G: the bit set is "on"
o_col:  !byte 31, 31, 31, 31, 31, 31, 31, 14
o_lo:   !byte <o_f, <o_p, <o_u, <o_m, <o_a, 0, 0, <o_g
o_hi:   !byte >o_f, >o_p, >o_u, >o_m, >o_a, 0, 0, >o_g
ox_lo:  !byte <o_x1, <o_x3, <o_x1, <o_x4, <o_x5, 0, 0       ; by descriptor index
ox_hi:  !byte >o_x1, >o_x3, >o_x1, >o_x4, >o_x5, 0, 0
o7_lo:  !byte <o_s, 0, <o_v, <o_w, 0, 0, <o_h
o7_hi:  !byte >o_s, 0, >o_v, >o_w, 0, 0, >o_h

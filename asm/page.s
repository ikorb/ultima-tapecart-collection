;;; A/X/Y = a flash address (lo, mid, hi): one page, or two, into BUF
fread1: sta tc_addr
        stx tc_addr+1
        sty tc_addr+2
        lda #>BUF
        ldx #$01
        jmp fread_to
fread2: sta tc_addr
        stx tc_addr+1
        sty tc_addr+2
        lda #>BUF
        ldx #$02
;;; X pages from tc_addr to page A
fread_to:
        sta tc_dest+1
        stx tc_len+1
        lda #$00
        sta tc_dest
        sta tc_len
        jmp tc_read

;;; Z set if BUF starts with a slot header's A5 5A
magic_ok:
        lda BUF
        cmp #$a5
        bne +
        lda BUF+1
        cmp #$5a
+       rts

;;; A party member's line: the name at (ptr), A letters (see prname), the
;;; status letter at +Y, hit points at +X and their maximum at +X+2 (BCD,
;;; high byte first), the hit points right-aligned in mwid columns, so the
;;; slashes line up.  member_nums: A = 0, the name is already out.
member:
        sty mstat
        stx mhp
        jsr prname
        jmp +
member_nums:
        sty mstat
        stx mhp
+       inc has_save
        ldy mstat
        lda (ptr),y
        jsr pchar               ; the status letter, a capital
        jsr CHROUT
        jsr pr
        !pet "  HP ",0
        lda mwid
        sta nwid
        ldy mhp
        lda (ptr),y
        tax
        iny
        lda (ptr),y
        sta mlo
        txa
        ldx mlo
        jsr prbcd16
        lda #"/"
        jsr CHROUT
        ldy mhp
        iny
        iny
        lda (ptr),y
        tax
        iny
        lda (ptr),y
        sta mlo
        txa
        ldx mlo
        jsr prbcd16
        lda #13
        jmp CHROUT


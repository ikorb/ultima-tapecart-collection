;;; ---- Ultima I: four characters, each its own save ----------------
;;; The roster (RO): four 16-byte records, +0 $FF if the slot is used,
;;; +3 the name, 13 bytes.  A character's record (P0-P3, 458 bytes):
;;; +0 CA 01, +$59 hit points and +$78 food, 16-bit binary.  U1 has no
;;; maximum.  Both slots: a header page (A5 5A len) then the data.
i_u1:   lda #<U1_RO
        ldx #>U1_RO
        ldy #^U1_RO
        jsr fread2
        jsr magic_ok
        beq +
        rts
+       lda #$00
        sta seat
i1_next:
        lda seat
        asl
        asl
        asl
        asl
        tax
        lda BUF+$100,x
        cmp #$ff
        beq +
        jmp i1_skip
+       inc has_save
        txa                     ; the name
        clc
        adc #<(BUF+$103)
        sta ptr
        lda #>(BUF+$103)
        sta ptr+1
        jsr pr
        !pet "   ",0
        lda #13
        jsr prname
        lda seat                ; the character's own slot
        asl
        asl
        asl
        asl
        clc
        adc #>U1_P0
        tax
        lda #^U1_P0
        adc #$00
        tay
        lda #<U1_P0
        jsr fread2
        jsr magic_ok
        bne i1_nodata
        lda BUF+$100
        cmp #$ca
        bne i1_nodata
        lda BUF+$101
        cmp #$01
        bne i1_nodata
        jsr pr
        !pet "HP ",0
        lda #4                  ; both to 9999 (Ztats): right-aligned in 4
        sta nwid
        lda BUF+$159
        ldx BUF+$15a
        jsr prdec16
        jsr pr
        !pet "  Food ",0
        lda #4
        sta nwid
        lda BUF+$178
        ldx BUF+$179
        jsr prdec16
        jmp i1_eol
i1_nodata:
        jsr pr
        !pet "(no data)",0
i1_eol: lda #13
        jsr CHROUT
        lda #<U1_RO             ; the roster again, for the next one
        ldx #>U1_RO
        ldy #^U1_RO
        jsr fread2
i1_skip:
        inc seat
        lda seat
        cmp #$04
        beq i1_out
        jmp i1_next
i1_out: rts

;;; ---- Ultima II: one character, the record at T35/S16 ---------------
;;; +0 the name (bit 7 set, NUL), +$1B hit points and +$1D food (BCD,
;;; high byte first), +$FF 0 on a player disk.  No maximum.
i_u2:   lda #<U2_REC            ; its seed, or its newest in the log
        sta tc_addr
        lda #>U2_REC
        sta tc_addr+1
        lda #^U2_REC
        sta tc_addr+2
        lda #$00
        jsr lg_find
        lda #>BUF
        ldx #$01
        jsr fread_to
        lda BUF
        cmp #$c1
        bcc i2_out
        cmp #$db
        bcs i2_out
        lda BUF+$ff
        bne i2_out
        inc has_save
        lda #<BUF
        sta ptr
        lda #>BUF
        sta ptr+1
        jsr pr
        !pet "   ",0
        lda #11
        jsr prname
        jsr pr
        !pet "HP ",0
        lda #4                  ; four BCD digits each, right-aligned
        sta nwid
        lda BUF+$1b
        ldx BUF+$1c
        jsr prbcd16
        jsr pr
        !pet "  Food ",0
        lda #4
        sta nwid
        lda BUF+$1d
        ldx BUF+$1e
        jsr prbcd16
        lda #13
        jsr CHROUT
i2_out: rts

;;; ---- Ultima III: the party, from PRTY and PLRS ----------------------
;;; PRTY +1 the party's size (0: none formed).  PLRS: four 64-byte
;;; records, +0 the name (bit 7 set, NUL), +$11 the status letter, +$1A
;;; hit points, +$1C their maximum (BCD, high byte first).
i_u3:   lda #<U3_PRTY
        ldx #>U3_PRTY
        ldy #^U3_PRTY
        jsr fread2
        jsr magic_ok
        bne i3_out
        lda BUF+$101
        beq i3_out
        cmp #$05
        bcs i3_out
        sta count
        lda #<U3_PLRS
        ldx #>U3_PLRS
        ldy #^U3_PLRS
        jsr fread2
        jsr magic_ok
        bne i3_out
        lda #<(BUF+$100)
        sta ptr
        lda #>(BUF+$100)
        sta ptr+1
-       jsr pr
        !pet "   ",0
        lda #4                  ; hit points: four BCD digits
        sta mwid
        lda #13
        ldy #$11                ; status
        ldx #$1a                ; hit points, then the maximum
        jsr member
        lda ptr
        clc
        adc #64
        sta ptr
        dec count
        bne -
i3_out: rts

;;; ---- Ultima IV: the party, from the roster block ---------------------
;;; Block 275 (zero page $10-$2F) +$0F: the party's size, 0 = no game.
;;; Block 273: eight 32-byte records, +0 the name (bit 7 set, NUL, 15 at
;;; most), +$12 the status, +$18 hit points, +$1A their maximum (BCD).
i_u4:   lda #<U4_ZP
        ldx #>U4_ZP
        ldy #^U4_ZP
        jsr fread1
        lda BUF+$0f
        beq i4_out
        cmp #$09
        bcs i4_out
        sta count
        lda #<U4_ROSTER
        ldx #>U4_ROSTER
        ldy #^U4_ROSTER
        jsr fread1
        lda #<BUF
        sta ptr
        lda #>BUF
        sta ptr+1
-       jsr pr
        !pet "   ",0
        lda #3                  ; hit points to 800
        sta mwid
        lda #15
        ldy #$12
        ldx #$18
        jsr member
        lda ptr
        clc
        adc #32
        sta ptr
        dec count
        bne -
i4_out: rts

;;; ---- Ultima V: the party, from the roster ---------------------------
;;; ROSTER (a slot: header page, then 1025 bytes): +0 sixteen 8-byte
;;; names (bit 7 set but on the last letter), +$80 sixteen 16-byte records:
;;; +0 $00 = in the party (only records 0-5 can be), +3 status, +8 hit
;;; points, +$A their maximum (BCD).  Byte 0 zero: no character yet.
i_u5:   lda #<U5_ROSTER
        ldx #>U5_ROSTER
        ldy #^U5_ROSTER
        jsr fread2
        jsr magic_ok
        bne i5_out
        lda BUF+$100
        beq i5_out
        lda #$00
        sta seat
i5_next:
        lda seat                ; the record
        asl
        asl
        asl
        asl
        tax
        lda BUF+$180,x
        bne i5_skip
        stx rec
        lda seat                ; its name
        asl
        asl
        asl
        clc
        adc #<(BUF+$100)
        sta ptr
        lda #>(BUF+$100)
        sta ptr+1
        jsr pr
        !pet "   ",0
        lda #$88                ; 8 letters, the last with bit 7 clear
        jsr prname
        lda rec                 ; the record
        clc
        adc #<(BUF+$180)
        sta ptr
        lda #>(BUF+$180)
        sta ptr+1
        lda #3                  ; hit points to 240 (30 a level)
        sta mwid
        lda #$00                ; no name here: just the numbers
        ldy #$03
        ldx #$08
        jsr member_nums
i5_skip:
        inc seat
        lda seat
        cmp #$06
        bne i5_next
i5_out: rts

;;; ---- Akalabeth: it saves nothing ------------------------------------
i_u0:   rts

;;; ---- Ultima VI: the party, from the newest save in the write log ----
;;; The save area is 1A T6 S9-20 ($5400-$5FFF); the party is in S12 and
;;; S13, keyed 01 00 06 0C and 01 00 06 0D in the log.  The log's active
;;; half is found as init_u6.s finds it: a half's top slot holds its first
;;; entry (generation 0) or a header ($FE "LOG", generation, complement);
;;; the valid half with the higher generation wins.  Its entries run down
;;; from the top until an erased key.  Not in the log: never saved.
;;;
;;; S13 +$8C the party's size - 1, +$8D.. the members' actor numbers.  S12
;;; +$6E fifteen actor numbers, one per named character (slot); +$7D the
;;; slot's name offset into S12; +$E8 its hit points; the maximum: slot 0
;;; at S12 +$FF, slots 1-14 at S13 +$00.  Names: capitals $41-$5A, the
;;; rest $01-$1A.
i_u6:   jsr u6_find_log
        bcc +
i6_no:  rts                     ; a fresh log: never saved
+       lda #$0c                ; S12 into BUF, S13 into BUF+$100
        ldx #>BUF
        jsr u6_sector
        bcs i6_no
        lda #$0d
        ldx #>(BUF+$100)
        jsr u6_sector
        bcs i6_no
        inc has_save
        jsr t_isnew             ; a new Avatar: T offers the transfer
        lda BUF+$18c            ; six members at most ($588D-$5892)
        cmp #$06
        bcs i6_out
        sta count
        inc count
        lda #$00
        sta seat
i6_next:
        ldx seat                ; the member's actor number, and its slot
        lda BUF+$18d,x
        ldy #14
-       cmp BUF+$6e,y
        beq +
        dey
        bpl -
        jmp i6_skip             ; not a named character
+       sty rec
        lda BUF+$7d,y           ; its name
        sta ptr
        lda #>BUF
        sta ptr+1
        jsr pr
        !pet "   ",0
        lda #13
        jsr prname
        jsr pr
        !pet "HP ",0
        lda #3                  ; a byte, right-aligned
        sta nwid
        ldy rec
        lda BUF+$e8,y
        ldx #$00
        jsr prdec16
        lda #"/"
        jsr CHROUT
        ldy rec
        lda BUF+$ff,y           ; slot 0 at S12 +$FF, 1-14 at S13 +0..
        ldx #$00
        jsr prdec16
        lda #13
        jsr CHROUT
i6_skip:
        inc seat
        dec count
        bne i6_next
i6_out: rts

;;; the log's active half, as init_u6.s picks it: C clear, act = 0 or 3,
;;; gen its generation, and ep/dcount its directory; C set if neither half
;;; is valid (a fresh log)
u6_find_log:
        ldx #$00                ; half 0
        jsr u6_top
        sta ok0
        lda tgen
        sta gen0
        lda tgen+1
        sta gen0+1
        ldx #$03                ; half 1
        jsr u6_top
        beq fl_h0               ; half 1 invalid: half 0 (if that is)
        lda ok0
        beq fl_h1               ; half 0 invalid
        lda tgen+1              ; both: half 1 if its generation is higher
        cmp gen0+1
        bcc fl_h0
        bne fl_h1
        lda gen0
        cmp tgen
        bcs fl_h0
fl_h1:  lda tgen
        sta gen
        lda tgen+1
        sta gen+1
        ldx #$03
        bne fl_scan
fl_h0:  lda ok0
        bne +
        sec                     ; neither
        rts
+       lda gen0
        sta gen
        lda gen0+1
        sta gen+1
        ldx #$00
fl_scan:
        stx act
        ;; count its entries: probe each key byte down from the top
        lda u6_tops,x
        sta ep
        lda u6_tops+1,x
        sta ep+1
        lda u6_tops+2,x
        sta ep+2
        lda #$00
        sta dcount
        sta dcount+1
-       jsr ep_down
        lda ep
        sta tc_addr
        lda ep+1
        sta tc_addr+1
        lda ep+2
        sta tc_addr+2
        lda #<probe
        sta tc_dest
        lda #>probe
        sta tc_dest+1
        lda #$01
        sta tc_len
        lda #$00
        sta tc_len+1
        jsr tc_read
        lda probe
        cmp #$ff
        beq +
        inc dcount
        bne -
        inc dcount+1
        bne -
+       lda ep                  ; the directory starts one slot up
        clc
        adc #ENTRY
        sta ep
        bcc +
        inc ep+1
        bne +
        inc ep+2
+       clc
        rts

;;; ep -= one entry
ep_down:
        sec
        lda ep
        sbc #ENTRY
        sta ep
        lda ep+1
        sbc #$00
        sta ep+1
        lda ep+2
        sbc #$00
        sta ep+2
        rts

;;; half X's (0 or 3) top slot: A = 1 (Z clear) if the half is valid, and
;;; tgen its generation; A = 0 (Z set) if not
u6_top: lda u6_tops,x
        sta ep
        lda u6_tops+1,x
        sta ep+1
        lda u6_tops+2,x
        sta ep+2
        jsr ep_down
        lda ep
        sta tc_addr
        lda ep+1
        sta tc_addr+1
        lda ep+2
        sta tc_addr+2
        lda #<ent
        sta tc_dest
        lda #>ent
        sta tc_dest+1
        lda #ENTRY
        sta tc_len
        lda #$00
        sta tc_len+1
        sta tgen
        sta tgen+1
        jsr tc_read
        lda ent
        cmp #$ff
        beq ut_bad              ; erased
        cmp #$fe
        bne ut_ok               ; an ordinary entry: generation 0
        ldx #$02
-       lda ent+1,x
        cmp log_name,x
        bne ut_bad
        dex
        bpl -
        lda ent+KEYLEN
        eor ent+KEYLEN+2
        cmp #$ff
        bne ut_bad
        lda ent+KEYLEN+1
        eor ent+KEYLEN+3
        cmp #$ff
        bne ut_bad
        lda ent+KEYLEN
        sta tgen
        lda ent+KEYLEN+1
        sta tgen+1
ut_ok:  lda #$01
        rts
ut_bad: lda #$00
        rts

;;; the newest logged copy of 1A T6 S(A) into page X: DIR_LOOKUP in the
;;; directory at ep, dcount entries.  C set if it is not there.
u6_sector:
        sta skey+3
        stx dpage
        jsr tc_enter
        lda #CMD_DIR_SETPARAMS
        jsr tc_sendbyte
        ldy #$00                ; (Y: tc_sendbyte and tc_getbyte keep
-       lda ep,y                ; only Y) address (3) and count (2), adjacent
        jsr tc_sendbyte
        iny
        cpy #$05
        bne -
        lda #KEYLEN
        jsr tc_sendbyte
        lda #DATALEN
        jsr tc_sendbyte
        lda #CMD_DIR_LOOKUP
        jsr tc_sendbyte
        ldy #$00
-       lda skey,y
        jsr tc_sendbyte
        iny
        cpy #KEYLEN
        bne -
        jsr tc_getbyte
        bne us_miss
        ldy #$00
-       jsr tc_getbyte          ; address (3), then the rest
        sta reply,y
        iny
        cpy #DATALEN
        bne -
        jsr tc_leave
        lda reply
        sta tc_addr
        lda reply+1
        sta tc_addr+1
        lda reply+2
        sta tc_addr+2
        lda dpage
        ldx #$01
        jsr fread_to
        clc
        rts
us_miss:
        jsr tc_leave
        sec
        rts

